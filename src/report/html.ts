import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { ConsoleEntry, ExtensionEvent, RunResult, StepResult, TestResult } from '../types.js';
import { formatMs } from './markdown.js';

/**
 * A single self-contained HTML file. Screenshots are inlined as data URIs so the report can be
 * attached to an issue or opened from anywhere without its sibling directories.
 */
export function renderHtml(result: RunResult, outDir: string): string {
  const failed = result.totals.failed > 0;
  const title = `${escapeHtml(result.extension.name)} — extension test report`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${title}</title>
<style>${STYLES}</style>
</head>
<body class="${failed ? 'has-failures' : ''}">
<header>
  <div class="head-row">
    <div>
      <h1>${escapeHtml(result.extension.name)}</h1>
      <p class="sub">
        <code>${escapeHtml(result.extension.id)}</code>
        <span>v${escapeHtml(result.extension.version)}</span>
        <span>MV${result.extension.manifestVersion}</span>
        <span>${result.browser.headless ? 'headless' : 'headed'} chromium</span>
        <span>id via ${escapeHtml(result.extension.idSource)}</span>
      </p>
    </div>
    <div class="verdict ${failed ? 'fail' : 'pass'}">
      <strong>${failed ? `${result.totals.failed} failed` : 'All passed'}</strong>
      <span>${result.totals.passed}/${result.totals.tests} tests · ${formatMs(result.durationMs)}</span>
    </div>
  </div>
  <div class="stats">
    ${stat('Suites', result.totals.suites)}
    ${stat('Tests', result.totals.tests)}
    ${stat('Passed', result.totals.passed, 'ok')}
    ${stat('Failed', result.totals.failed, result.totals.failed ? 'bad' : '')}
    ${stat('Skipped', result.totals.skipped)}
  </div>
  ${manifestSummary(result)}
</header>

<main>
${result.suites.map((suite) => renderSuite(suite, outDir)).join('\n')}
</main>

<footer>Generated by ext-tester on ${escapeHtml(new Date(result.finishedAt).toLocaleString())}</footer>
<script>${SCRIPT}</script>
</body>
</html>`;
}

function renderSuite(suite: RunResult['suites'][number], outDir: string): string {
  return `<section class="suite">
  <h2>${escapeHtml(suite.name)} <span class="file">${escapeHtml(suite.file)}</span></h2>
  ${suite.tests.map((test) => renderTest(test, outDir)).join('\n')}
</section>`;
}

function renderTest(test: TestResult, outDir: string): string {
  const errors = test.console.filter((c) => c.type === 'error');
  return `<details class="test ${test.status}" ${test.status === 'failed' ? 'open' : ''}>
  <summary>
    <span class="badge ${test.status}">${test.status}</span>
    <span class="name">${escapeHtml(test.name)}</span>
    <span class="meta">${test.steps.length} steps · ${formatMs(test.durationMs)}${errors.length ? ` · ${errors.length} console error${errors.length > 1 ? 's' : ''}` : ''}</span>
  </summary>
  ${test.error ? `<div class="error-banner">${escapeHtml(test.error)}</div>` : ''}
  <ol class="steps">
    ${test.steps.map((step) => renderStep(step, outDir)).join('\n')}
  </ol>
  ${renderConsole(test.console)}
  ${renderEvents(test.events ?? [])}
  ${test.video ? `<p class="video">Video: <code>${escapeHtml(test.video)}</code></p>` : ''}
</details>`;
}

function renderEvents(events: ExtensionEvent[]): string {
  if (!events.length) return '';
  return `<details class="console events">
  <summary>Extension events (${events.length})</summary>
  <ul>
  ${events
    .map(
      (event) =>
        `<li><span class="ctx">${escapeHtml(event.source)}</span><span class="lvl">${escapeHtml(event.type)}</span><span class="txt">${escapeHtml(preview(event.detail))}</span></li>`,
    )
    .join('\n')}
  </ul>
</details>`;
}

function renderStep(step: StepResult, outDir: string): string {
  const shot = step.screenshot ? inlineImage(join(outDir, step.screenshot)) : undefined;
  return `<li class="step ${step.status}">
  <div class="step-head">
    <span class="dot ${step.status}"></span>
    <code class="action">${escapeHtml(step.action)}</code>
    <span class="desc">${escapeHtml(step.description)}</span>
    <span class="dur">${formatMs(step.durationMs)}</span>
  </div>
  ${step.error ? `<pre class="err">${escapeHtml(step.error)}</pre>` : ''}
  ${step.value !== undefined ? `<pre class="value">→ ${escapeHtml(preview(step.value))}</pre>` : ''}
  ${shot ? `<figure><img loading="lazy" src="${shot}" alt="${escapeHtml(step.description)}"></figure>` : ''}
</li>`;
}

function renderConsole(entries: ConsoleEntry[]): string {
  if (!entries.length) return '';
  const errors = entries.filter((e) => e.type === 'error').length;
  return `<details class="console">
  <summary>Console (${entries.length}${errors ? `, ${errors} errors` : ''})</summary>
  <ul>
  ${entries
    .map(
      (e) =>
        `<li class="lvl-${escapeHtml(e.type)}"><span class="ctx">${escapeHtml(e.context)}</span><span class="lvl">${escapeHtml(e.type)}</span><span class="txt">${escapeHtml(e.text)}</span></li>`,
    )
    .join('\n')}
  </ul>
</details>`;
}

function manifestSummary(result: RunResult): string {
  const ext = result.extension;
  const chips = [
    ext.popup ? `popup: ${ext.popup}` : null,
    ext.optionsPage ? `options: ${ext.optionsPage}` : null,
    ext.hasServiceWorker ? 'service worker' : null,
    ext.contentScripts.length ? `${ext.contentScripts.length} content script block(s)` : null,
    Object.keys(ext.commands).length ? `${Object.keys(ext.commands).length} command(s)` : null,
  ].filter(Boolean) as string[];
  const perms = [...ext.permissions, ...ext.hostPermissions];
  return `<div class="manifest">
    ${chips.map((c) => `<span class="chip">${escapeHtml(c)}</span>`).join('')}
    ${perms.length ? `<span class="chip perms" title="${escapeHtml(perms.join(', '))}">${perms.length} permission(s)</span>` : ''}
  </div>`;
}

function stat(label: string, value: number, tone = ''): string {
  return `<div class="stat ${tone}"><span class="n">${value}</span><span class="l">${label}</span></div>`;
}

/** Read a screenshot off disk and inline it. Missing files degrade to no image. */
function inlineImage(path: string): string | undefined {
  try {
    if (!existsSync(path)) return undefined;
    return `data:image/png;base64,${readFileSync(path).toString('base64')}`;
  } catch {
    return undefined;
  }
}

function preview(value: unknown): string {
  const text = typeof value === 'string' ? value : JSON.stringify(value);
  return text != null && text.length > 400 ? `${text.slice(0, 400)}…` : String(text);
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function writeHtmlReport(result: RunResult, outDir: string): string {
  const file = join(outDir, 'report.html');
  writeFileSync(file, renderHtml(result, outDir), 'utf8');
  return file;
}

